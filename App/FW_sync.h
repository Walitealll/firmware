#ifndef FW_SYNC_H
#define FW_SYNC_H

/* Запускает сетку 5 мс. Измерения и пакет 100 Гц отсюда не идут. */
void FW_sync_start(void);
/* Вызывается при входе в CONNECTED. Следующий кадр питания — через 10 с, не сразу. */
void FW_sync_power_arm(void);
/* Вызывается при разрыве. Пока телефона нет, кадр питания не назревает. */
void FW_sync_power_stop(void);
/* 1 — пора класть кадр питания. Пока связь не отмечена, такты только забирает и возвращает 0. */
int FW_sync_power_due(void);

/* Вызывается из главного цикла каждый проход, раньше разбора BLE.
   В MEASUREMENT забирает окно ЭМГ, считает угол и кладёт кадр 0x03 в очередь.
   Вне измерения съём ЭМГ гасит. Недособранное окно не отправляет. */
void FW_sync_poll(void);
/* STOP и обрыв связи. Гасит съём сразу, не дожидаясь следующего прохода цикла. */
void FW_sync_stop(void);

#endif /* FW_SYNC_H */
