#ifndef FW_HW_H
#define FW_HW_H

#include <stdint.h>

/* Общий список вызовов к плате. FW_* подключают этот файл и не вызывают HAL сами.
   Тела функций лежат в gpio.c, adc.c, usart.c, i2c.c и tim.c. */

/* Чем кончился один вызов к шине или АЦП. */
typedef enum {
  FW_HW_OK = 0,       /* действие сделано */
  FW_HW_ERR = -1,     /* шина или параметр сломались, повторять вслепую не стоит */
  FW_HW_TIMEOUT = -2, /* ждали байт и не дождались */
  FW_HW_ABSENT = -3   /* на I2C по этому адресу никто не ответил, это не поломка шины */
} fw_hw_status_t;

/* Какая из двух шин датчиков. Номер совпадает с I2C1 и I2C2 в Cube. */
typedef enum {
  FW_HW_I2C1 = 1,
  FW_HW_I2C2 = 2
} fw_hw_i2c_bus_t;

/* Какой датчик угла сбрасываем. Какая шина ему соответствует, здесь не записано: это узнают по пропаже с шины. */
typedef enum {
  FW_HW_BNO_INTERNAL = 0,
  FW_HW_BNO_EXTERNAL = 1
} fw_hw_bno_id_t;

/* Вызывается перед BLE и датчиками. 1 — такт 72 МГц, как в схеме. */
int fw_hw_clock_ready(void);
/* Вызывается перед первой командой AT. 1 — USART1 уже настроен на модуль, заново его не поднимаем. */
int fw_hw_uart_ready(void);
/* Вызывается перед поиском BNO055. 1 — обе шины на 100 кГц и датчику разрешено тянуть такт. */
int fw_hw_i2c_ready(void);
/* Вызывается перед чтением батареи. 1 — ADC2 уже поднят в main, само измерение ниже. */
int fw_hw_adc_battery_ready(void);
/* Вызывается в конце настройки ADC1. Единственный вход ЭМГ — PB0, канал 8.
   Время выборки берётся из FW_EMG_ADC_SAMPLETIME, в ранг 1 ставится FW_EMG_ADC_CH. */
void fw_hw_adc_emg_bind(void);

/* Берут для строки лога и чтобы дождаться 200 мс на MOD. Это тик HAL, не таймер измерений 5 мс. */
uint32_t fw_hw_tick_ms(void);
/* Запускает таймер сетки 5 мс. В прерывании только счётчик, разбор кадра там не делается. */
void fw_hw_timer_5ms_start(void);
/* Забирает, сколько тактов 5 мс прошло с прошлого вызова. 0 — новых не было. */
uint32_t fw_hw_timer_5ms_take(void);
/* Миллисекунды той же сетки 5 мс с момента старта таймера. Счётчик не обнуляется и на START не сбрасывается. */
uint32_t fw_hw_timer_5ms_ms(void);
/* Вызывается, когда инициализации надо переждать известное время: пробуждение, смена режима датчика. */
void fw_hw_delay_ms(uint32_t delay_ms);

/* Вызывается при каждой проверке батареи. 1 — PGOOD в нуле, зарядник видит источник. */
int fw_hw_pgood_is_low(void);
/* 1 — кабель вставлен. Какой пин это решает, задаёт FW_CABLE_SRC. */
int fw_hw_cable_present(void);
/* Вызывается при сборке кадра питания. 1 — CHG в нуле, ток в батарею идёт. */
int fw_hw_chg_is_low(void);
/* Одно измерение узла CAP: ADC2, PA0. Кладёт сырой код. В милливольты не переводит. */
fw_hw_status_t fw_hw_adc_battery_raw(uint16_t *raw);

/* Вход в MEASUREMENT. Запускает TIM3 и кольцо DMA ЭМГ. Повторный вызов ничего не перезапускает. */
fw_hw_status_t fw_hw_emg_start(void);
/* Выход из MEASUREMENT. Таймер, АЦП и канал DMA гасятся, признак ошибки АЦП снимается. */
void fw_hw_emg_stop(void);
/* Одна готовая половина кольца. 1 — в dst лежит FW_EMG_FRAME_COUNT кодов по порядку.
   0 — новой половины нет. -1 — окно пропущено, dst не смотреть. */
int fw_hw_emg_take(uint16_t *dst);

/* Вызывается в начале инициализации. Поднимает виртуальный COM на USB, чтобы текст дождался терминала. */
void fw_hw_usb_start(void);
/* Кладёт готовый текст инициализации. Уходит, когда терминал открыл порт, и ещё раз при повторном открытии. */
void fw_hw_usb_send(const uint8_t *data, uint16_t len);

/* Вызывается в инициализации до BLE. Пишет в AD5160 код FW_DP_WIPER_MIN. Ответа у микросхемы нет. */
fw_hw_status_t fw_hw_dp_wiper_min(void);

/* Вызывается в начале настройки BLE. Держит сброс модуля отпущенным, импульс не делает. */
void fw_hw_ble_rst_idle(void);
/* Низкий MOD на время защёлки. До соединения команды AT от этого уровня не зависят. */
void fw_hw_ble_mod_low(void);
/* Высокий MOD после спада. После соединения с этим уровнем байты идут на телефон. */
void fw_hw_ble_mod_high(void);
/* Вызывается в конце защёлки. 1 — MOD остался высоким. */
int fw_hw_ble_mod_is_high(void);
/* Вызывается один раз, если модуль не ответил на AT. Даёт спад на WKP и держит его низким 200 мс. */
void fw_hw_ble_wake(void);

/* Шлёт команде AT ровно те байты, которые передали. Конец строки сам не добавляет. */
fw_hw_status_t fw_hw_uart_tx(const uint8_t *data, uint16_t len);
/* Читает один байт ответа. timeout_ms = 0 значит «если байт уже лежит — забери, иначе сразу вернись».
   Это опрос для команд AT. После инициализации приём идёт прерыванием, не этим вызовом. */
fw_hw_status_t fw_hw_uart_rx(uint8_t *byte, uint32_t timeout_ms);
/* Включает приём USART1 в прерывание. Повторный вызов ничего не делает, если приём уже стоит.
   1 — кольцо пополняется. 0 — прерывание включить не удалось, байты в кольцо не попадут. */
int fw_hw_uart_rx_listen(void);
/* Забирает один байт, который прерывание уже сложило в кольцо. Пустое кольцо — FW_HW_TIMEOUT. */
fw_hw_status_t fw_hw_uart_take(uint8_t *byte);
/* Сколько байт кольцо выкинуло с прошлого вызова, потому что места не было. */
unsigned fw_hw_uart_rx_drop_take(void);
/* Ставит байты на DMA и сразу возвращается. Буфер должен жить, пока передача не кончится.
   Канал включается на этот кадр и сам выключается. Следующий кадр сам не стартует. */
fw_hw_status_t fw_hw_uart_tx_dma(const uint8_t *data, uint16_t len);
/* 1 один раз, когда кадр дописан до конца сдвигового регистра.
   Колбэк DMA этого не делает: он только включает прерывание TC, а этот флаг ставит уже оно.
   Пока биты ещё идут, возвращает 0. */
int fw_hw_uart_tx_done(void);
/* 1 — передача не идёт и бит TC стоит, предыдущий кадр уже вышел на линию.
   0 — рано начинать следующий кадр. */
int fw_hw_uart_tx_line_idle(void);

/* Макет. Ставит сброс выносного BNO на PB1 в то же состояние, что у штатного пина: отпущен, единица. */
void fw_hw_ext_bno_rst_demo_init(void);
/* Вызывается, когда надо понять, какой датчик внутренний или внешний. Держит его сброс в нуле. */
void fw_hw_bno_reset_hold(fw_hw_bno_id_t id);
/* Вызывается перед ожиданием выхода датчика в режим настройки. Отпускает сброс. */
void fw_hw_bno_reset_release(fw_hw_bno_id_t id);

/* Спрашивает, есть ли датчик. FW_HW_ABSENT — адреса нет, FW_HW_ERR — шина не в порядке. */
fw_hw_status_t fw_hw_i2c_probe(fw_hw_i2c_bus_t bus, uint8_t addr7);
/* Пишет один регистр датчика. addr7 — семь бит адреса, без бита чтения. */
fw_hw_status_t fw_hw_i2c_write_reg(fw_hw_i2c_bus_t bus, uint8_t addr7, uint8_t reg, uint8_t value);
/* Читает один регистр, например режим или единицы. */
fw_hw_status_t fw_hw_i2c_read_reg(fw_hw_i2c_bus_t bus, uint8_t addr7, uint8_t reg, uint8_t *value);
/* Читает несколько байт подряд. Для кватерниона это обязательно: по одному байту отсчёт разъезжается. */
fw_hw_status_t fw_hw_i2c_read(fw_hw_i2c_bus_t bus, uint8_t addr7, uint8_t reg, uint8_t *data, uint16_t len);

#endif /* FW_HW_H */
