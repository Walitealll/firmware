#ifndef FW_BLE_H
#define FW_BLE_H

#include <stdint.h>

/* Вызывается из FW_init после проверки батареи и до датчиков угла.
   Будит модуль, если он молчит, записывает настройки, проверяет их и гасит эфир.
   Защёлка MOD — спад и подъём по 200 мс, когда модуль уже ответил после своего сброса.
   Обмен с телефоном не начинает. code заполняется, если шаг не прошёл. Возврат 0 — успех. */
int FW_ble_init(const char **code);
/* На каком шаге остановилась последняя FW_ble_init.
   -1 — нет ответа AT. 0 — AT есть, запись настройки не принялась.
   1 — скорость не 10. 2 — после скорости другая настройка не принялась.
   3 — статус не 1. 4 — реклама не 1. 5 — MOD не удержался.
   6 — проверка сошлась и эфир погашен. 7 — AT+ADV=0 не принят.
   8 — интервал связи не 6,0,400. */
int FW_ble_init_stage(void);

/* Вызывается из FW_init после успешных датчиков, до смены режима.
   Сначала включает приём в кольцо, затем шлёт AT+ADV=1 и ждёт +OK.
   Строку соединения, пришедшую в этом окне, запоминает. code — при отказе. Возврат 0 — эфир включён. */
int FW_ble_advertising_on(const char **code);
/* Вызывается, если эфир уже включили, а переход в ADVERTISING не пустил. Шлёт AT+ADV=0. */
void FW_ble_advertising_off(void);
/* Вызывается сразу после входа в ADVERTISING. Соединение, пришедшее раньше смены режима, переводит в CONNECTED. */
void FW_ble_accept_early_link(void);

/* Вызывается из главного цикла после инициализации, на каждом обороте.
   В ADVERTISING, CONNECTED и MEASUREMENT забирает уже принятые байты.
   Строка соединения переводит в CONNECTED, строка разрыва возвращает в ADVERTISING.
   Пока телефон подключён, раз в 10 с кладёт кадр питания.
   START без кабеля переводит в MEASUREMENT, ответа нет.
   START при кабеле остаётся в CONNECTED и кладёт событие 1.
   STOP из MEASUREMENT возвращает в CONNECTED, гасит съём и кладёт событие 3.
   STOP уже из CONNECTED тоже кладёт событие 3.
   Другое число режим не меняет и на телефон не уходит, отказ пишется в диагностику.
   DMA забирает один кадр и сам выключается. Следующий стартует не раньше 10 мс
   и только после того, как предыдущий полностью ушёл в линию. */
void FW_ble_poll(void);
/* Кладёт уже собранный кадр измерения в очередь UART. Пускает только из MEASUREMENT.
   0 — кадр в очереди. -1 — режим другой, буфер пустой или места в очереди нет. */
int FW_ble_send(const uint8_t *data, unsigned len);

#endif /* FW_BLE_H */
