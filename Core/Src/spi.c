/* Вызывается в инициализации. CS опускается на время одного байта и снова поднимается:
   по фронту CS микросхема переписывает байт в движок. Читать в ответ нечего. */
fw_hw_status_t fw_hw_dp_wiper_min(void)
{
  uint8_t code = (uint8_t)FW_DP_WIPER_MIN;
  HAL_StatusTypeDef status;

  HAL_GPIO_WritePin(GPIO_OUT_DP_CS_GPIO_Port, GPIO_OUT_DP_CS_Pin, GPIO_PIN_RESET);
  status = HAL_SPI_Transmit(&hspi1, &code, 1u, FW_IO_TIMEOUT_MS);
  HAL_GPIO_WritePin(GPIO_OUT_DP_CS_GPIO_Port, GPIO_OUT_DP_CS_Pin, GPIO_PIN_SET);
  if (status != HAL_OK) {
    return FW_HW_ERR;
  }
  return FW_HW_OK;
}

